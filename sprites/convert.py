#!/usr/bin/env python3
"""Convert sprites/*.txt (ASCII frames, '#' = lit) into firmware/src/sprites.h and sprites/preview.png.

Each .txt: first line `ms=<frame time>`, then frames of 32x40 chars separated by blank lines.
Frames are scaled 2x on the device (64x80 px on the portrait 64x128 screen).
"""
import os, struct, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_H = os.path.join(HERE, '..', 'firmware', 'src', 'sprites.h')
OUT_PNG = os.path.join(HERE, 'preview.png')
W, H, SCALE = 32, 40, 2
ANIMS = ['sleep', 'idle', 'coding', 'video', 'music', 'meeting', 'chill', 'poke', 'coffee', 'drowsy']


def load(name):
    path = os.path.join(HERE, name + '.txt')
    head, *rest = open(path).read().strip().split('\n\n')
    assert head.startswith('ms='), f'{path}: first line must be ms=<number>'
    frames = []
    for i, block in enumerate(rest):
        rows = block.split('\n')
        assert len(rows) == H, f'{path} frame {i}: {len(rows)} rows, need {H}'
        for r in rows:
            assert len(r) == W and set(r) <= {'#', '.'}, f'{path} frame {i}: bad row {r!r} (need {W} of # or .)'
        frames.append([[ch == '#' for ch in r] for r in rows])
    return int(head[3:]), frames


def xbm(frame):  # scaled, LSB-first rows as u8g2 drawXBMP expects
    out = []
    for r in frame:
        bits = [b for b in r for _ in range(SCALE)]
        row = [sum(1 << i for i in range(8) if bits[x + i]) for x in range(0, len(bits), 8)]
        out += row * SCALE
    return out


def png(path, rows):  # rows: list of lists of (r,g,b)
    raw = b''.join(b'\0' + bytes(c for px in r for c in px) for r in rows)
    chunk = lambda t, d: struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d))
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', len(rows[0]), len(rows), 8, 2, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))


def main():
    anims = {n: load(n) for n in ANIMS}
    h = ['// Generated by sprites/convert.py — edit the .txt files, not this.', '#pragma once', '#include <stdint.h>',
         f'#define SPRITE_W {W * SCALE}', f'#define SPRITE_H {H * SCALE}',
         'struct Anim { const uint8_t* const* frames; uint8_t count; uint16_t ms; };']
    for n, (ms, frames) in anims.items():
        for i, f in enumerate(frames):
            h.append(f'static const uint8_t {n}_{i}[] = {{{",".join(str(b) for b in xbm(f))}}};')
        h.append(f'static const uint8_t* const {n}_frames[] = {{{", ".join(f"{n}_{i}" for i in range(len(frames)))}}};')
        h.append(f'static const Anim ANIM_{n.upper()} = {{{n}_frames, {len(frames)}, {ms}}};')
    open(OUT_H, 'w').write('\n'.join(h) + '\n')

    # preview: one row per animation, frames side by side, OLED-ish colors, 4x zoom
    Z, PAD, on, off, bg = 4, 4, (220, 235, 255), (0, 0, 0), (40, 40, 40)
    maxf = max(len(f) for _, f in anims.values())
    rows = []
    for _, frames in anims.values():
        for y in range(H * Z):
            line = []
            for fi in range(maxf):
                fr = frames[fi] if fi < len(frames) else None
                line += [(on if fr and fr[y // Z][x // Z] else off) if fr else bg for x in range(W * Z)] + [bg] * PAD
            rows.append(line)
        rows += [[bg] * len(rows[-1]) for _ in range(PAD)]
    png(OUT_PNG, rows)
    print(f'wrote {OUT_H} and {OUT_PNG}')


if __name__ == '__main__':
    main()
